# ---------------------------------------------------------------------------
#               High Level Control Plotter - Category 3
# ---------------------------------------------------------------------------
# Mid level: as in category 2, but the common reference path is the first path
# generated by the global planner (identical start/goal for every method).
# High level: distance from the executed trajectory to the planner path valid at
# each instant (the planner recomputes it at 1 Hz), plus path-quality indicators
# (length ratio, clearance, contacts, success, time to goal).

import os

import numpy as np
import rclpy
from nav_msgs.msg import Path

from benchmark_bringup.metrics import (
    dist_points_polyline,
    high_level_indices,
    mid_level_indices,
    path_length,
    path_quality,
)
from benchmark_bringup.plotter.common import run_recorder
from benchmark_bringup.plotter.nav_common import NavRecorder, prediction_error_series, fit_xy, stamp_to_sec

DEFAULT_GOAL = (18.0, 17.4)  # same as categories/categorie_3.py


class PlotterC3(NavRecorder):
    CATEGORY = 3

    def __init__(self):
        super().__init__("plotter_c3_benchmark")
        self.plans = []        # list of (t_wall, Nx2 array)
        self.create_subscription(Path, "/plan", self._cb_plan, 10)
        self.fig1 = self.fig2 = self.fig3 = None
        if self.plot:
            self._create_figures()
            self.plot_period = 1.0

    def _cb_plan(self, msg: Path):
        if self.done or not msg.poses:
            return
        t = stamp_to_sec(msg.header.stamp) or self.now()
        xy = np.array([[p.pose.position.x, p.pose.position.y] for p in msg.poses])
        self.plans.append((t, xy))

    # ----------------------------------------------------------------- helpers
    def goal(self):
        if self.route:
            return tuple(self.route[-1][:2])
        return DEFAULT_GOAL

    def plans_in_window(self, t0, t1):
        return [p for p in self.plans if p[0] <= t1]

    def first_plan(self, t0):
        after = [p for p in self.plans if p[0] >= t0 - 0.5]
        if after:
            return after[0][1]
        return self.plans[0][1] if self.plans else np.zeros((0, 2))

    # ----------------------------------------------------------------- metrics
    def compute_metrics(self) -> dict:
        t0, t1 = self.window()
        m = dict(self.low_level_metrics(t0, t1))
        tg, xg, yg, _ = self.cols(self.gt_rows, 4)
        tc, vc, wc = self.cols(self.cmd_rows, 3)
        ref = self.first_plan(t0)
        plans = self.plans_in_window(t0, t1)
        m.update(mid_level_indices(tg, xg, yg, tc, vc, wc, self.local_plans, self.cfg, t0, t1,
                                   ref_plans=plans))
        m.update(high_level_indices(tg, xg, yg, plans, self.cfg, t0, t1, first_plan=ref))
        ts, rs = self.cols(self.scan_rows, 2)
        ref_len = path_length(ref[:, 0], ref[:, 1]) if ref.shape[0] > 1 else None
        m.update(path_quality(tg, xg, yg, self.goal(), ts, rs, self.cfg, t0, t1,
                              reference_length=ref_len, final_status=self.final_status,
                              t_collision=self.cols(self.col_rows, 2)[0],
                              collision=self.cols(self.col_rows, 2)[1]))
        m["planned_path_length"] = ref_len if ref_len is not None else float("nan")
        m["JT3"] = self.total(m.get("J1"), m.get("J2"), m.get("J3"))
        return m

    def write_extra_csv(self, out_dir: str):
        super().write_extra_csv(out_dir)
        rows = []
        for k, (t, xy) in enumerate(self.plans):
            rows += [[k, t, x, y] for x, y in xy]
        self.write_csv(os.path.join(out_dir, "plans.csv"), ["plan_id", "t_wall", "x", "y"], rows)

    # ------------------------------------------------------------------ figures
    def _create_figures(self):
        from matplotlib.gridspec import GridSpec

        self.fig1, self.ax1 = self.create_low_level_figure(
            "Category 3: Low Level Control. Linear Velocities of Left and Right Wheels")
        self.fig2 = self.plt.figure(figsize=(17, 10))
        gs = GridSpec(3, 2, width_ratios=[3.6, 1.4], figure=self.fig2)
        self.ax_xy = self.fig2.add_subplot(gs[0, 0])
        self.ax_u = self.fig2.add_subplot(gs[1, 0])
        self.ax_e = self.fig2.add_subplot(gs[2, 0])
        self.ax_t2 = self.fig2.add_subplot(gs[:, 1])
        self.ax_t2.axis("off")
        self.fig3 = self.plt.figure(figsize=(17, 10))
        gs3 = GridSpec(2, 2, width_ratios=[3.6, 1.4], figure=self.fig3)
        self.ax_p = self.fig3.add_subplot(gs3[0, 0])
        self.ax_pe = self.fig3.add_subplot(gs3[1, 0])
        self.ax_t3 = self.fig3.add_subplot(gs3[:, 1])
        self.ax_t3.axis("off")

    def _draw(self):
        t0, t1 = self.window()
        m = self.compute_metrics()
        self.draw_low_level(self.fig1, self.ax1, t0)
        lb = self.last_bench
        rows1 = [("Control Params", "Values")]
        if lb is not None:
            rows1 += [("Kp", f"{lb.kp:.2f}"), ("Ki", f"{lb.ki:.2f}"), ("Kd", f"{lb.kd:.2f}"),
                      ("Anti-windup", "ON" if lb.enable_antiwindup else "OFF")]
        rows1 += [("Performance Index", ""), ("SAE1", self.fmt(m.get("SAE1"))),
                  ("SCI1", self.fmt(m.get("SCI1"))), ("J1", self.fmt(m.get("J1")))]
        self.draw_table(self.ax1["table"], rows1)
        self.fig1.tight_layout()

        tg, xg, yg = self.crop(t1, *self.cols(self.gt_rows, 4)[:3])
        ref = self.first_plan(t0)
        for ax in (self.ax_xy, self.ax_u, self.ax_e, self.ax_p, self.ax_pe):
            ax.cla()

        # Mid level
        self.ax_xy.set_title("Category 3: Mid Level Control. Trajectory tracking (ground truth)")
        self.ax_xy.plot(xg, yg, color="#2c41a0", label="Robot")
        if self.local_xy.shape[0]:
            self.ax_xy.plot(self.local_xy[:, 0], self.local_xy[:, 1], ".", color="#ff7f0e",
                            markersize=3, label=f"{self.controller.upper()} local path")
        self.ax_xy.set_xlabel("x [m]")
        self.ax_xy.set_ylabel("y [m]")
        fit_xy(self.ax_xy, np.column_stack([xg, yg]) if len(xg) else None, [self.goal()])
        self.ax_xy.legend(loc="best")
        self.ax_xy.grid(True)
        tc, vc, wc = self.crop(t1, *self.cols(self.cmd_rows, 3))
        self.ax_u.plot(tc - t0, vc, color="#1f77b4", label=r"$v$ [m/s]")
        self.ax_u.plot(tc - t0, wc, "--", color="#9467bd", label=r"$\omega$ [rad/s]")
        self.ax_u.set_ylabel("Command")
        self.ax_u.legend(loc="upper right")
        self.ax_u.grid(True)
        if tg.size and self.plans:
            t_pl = np.array([p[0] for p in self.plans])
            idx = np.clip(np.searchsorted(t_pl, tg, side="right") - 1, 0, None)
            e = np.full(tg.size, np.nan)
            for k in np.unique(idx):
                sel = idx == k
                e[sel] = dist_points_polyline(xg[sel], yg[sel], self.plans[k][1])
            self.ax_e.plot(tg - t0, e, color="#2ca02c",
                           label=f"Mid-level error, {self.controller.upper()} (distance to the current plan)")
        self.ax_e.set_xlabel("Time [s]")
        self.ax_e.set_ylabel("Error [m]")
        self.ax_e.legend(loc="upper right")
        self.ax_e.grid(True)
        rows2 = [("Performance Index", ""), ("SAE2", self.fmt(m.get("SAE2"))),
                 ("SCI2", self.fmt(m.get("SCI2"))), ("J2", self.fmt(m.get("J2")))]
        self.draw_table(self.ax_t2, rows2)
        self.fig2.tight_layout()

        # High level
        self.ax_p.set_title("Category 3: High Level Control. Global plan and executed trajectory")
        if self.plans:
            last = self.plans[-1][1]
            self.ax_p.plot(last[:, 0], last[:, 1], "--", color="#d62728", label="Current plan")
        if ref.shape[0]:
            self.ax_p.plot(ref[:, 0], ref[:, 1], ":", color="#7f7f7f", label="First plan")
        self.ax_p.plot(xg, yg, color="#2c41a0", label="Robot")
        g = self.goal()
        self.ax_p.scatter([g[0]], [g[1]], marker="x", s=80, color="#a50f15", label="Goal")
        self.ax_p.set_xlabel("x [m]")
        self.ax_p.set_ylabel("y [m]")
        fit_xy(self.ax_p, ref, np.column_stack([xg, yg]) if len(xg) else None, [g])
        self.ax_p.legend(loc="best")
        self.ax_p.grid(True)
        if tg.size and ref.shape[0] >= 2:
            self.ax_pe.plot(tg - t0, dist_points_polyline(xg, yg, ref), color="#2ca02c",
                            label="High-level error (distance to the first plan)")
        self.ax_pe.set_xlabel("Time [s]")
        self.ax_pe.set_ylabel("Error [m]")
        self.ax_pe.legend(loc="upper right")
        self.ax_pe.grid(True)
        for ax in (self.ax_u, self.ax_e, self.ax_pe):
            ax.set_xlim(left=0)
        rows3 = [(f"Planner: {self.planner.upper() or '-'}", ""),
                 ("Performance Index", ""), ("SAE3 = J3", self.fmt(m.get("SAE3"))),
                 ("JT3 = (J1+J2+J3)/3", self.fmt(m.get("JT3"))), ("Path quality", ""),
                 ("Planned length [m]", self.fmt(m.get("planned_path_length"))),
                 ("Executed length [m]", self.fmt(m.get("path_length"))),
                 ("Length ratio", self.fmt(m.get("length_ratio"))),
                 ("Min obstacle dist. [m]", self.fmt(m.get("min_obstacle_dist"))),
                 ("Contacts", self.fmt(m.get("contacts"))),
                 ("Success", self.fmt(m.get("success"))),
                 ("Time to goal [s]", self.fmt(m.get("time_to_goal")))]
        self.draw_table(self.ax_t3, rows3)
        self.fig3.tight_layout()

    def update_plot(self):
        if self.done:
            return
        self._draw()
        for f in (self.fig1, self.fig2, self.fig3):
            f.canvas.draw_idle()
            f.canvas.flush_events()

    def save_figures(self, out_dir: str):
        if self.fig1 is None:
            self._create_figures()
        self._draw()
        self.save_fig(self.fig1, os.path.join(out_dir, "category_3_low_level.png"))
        self.save_fig(self.fig2, os.path.join(out_dir, "category_3_mid_level.png"))
        self.save_fig(self.fig3, os.path.join(out_dir, "category_3_high_level.png"))


def main():
    rclpy.init()
    node = PlotterC3()
    run_recorder(node, node.plt if node.plot else None)


if __name__ == "__main__":
    main()
